import React, { useCallback, useEffect, useState } from 'react';
import { FlatList, StyleSheet, Text, View } from 'react-native';
import Card from '../../components/Card';
import Button from '../../components/Button';
import TrialGate from './TrialGate';
import { colors, spacing } from '../../theme';
import { getPayslips, PayslipListItem } from '../../api/payslipApi';

export default function PayslipsScreen({ navigation }: any) {
  const [year, setYear] = useState(new Date().getFullYear());
  const [payslips, setPayslips] = useState<PayslipListItem[]>([]);
  const [loading, setLoading] = useState(false);
  const [trial, setTrial] = useState(false);

  const load = useCallback(async () => {
    setLoading(true);
    try {
      const res = await getPayslips(year);
      setPayslips(res.data.payslips);
    } catch (err: any) {
      if (err?.response?.data?.code === 'TRIAL_PENDING') setTrial(true);
    } finally {
      setLoading(false);
    }
  }, [year]);

  useEffect(() => {
    load();
  }, [load]);

  if (trial) return <TrialGate navigation={navigation} />;

  return (
    <View style={styles.screen}>
      <View style={styles.yearRow}>
        <Button title="< Prev" variant="outline" onPress={() => setYear((y) => y - 1)} />
        <Text style={styles.yearLabel}>{year}</Text>
        <Button title="Next >" variant="outline" onPress={() => setYear((y) => y + 1)} />
      </View>

      <FlatList
        data={payslips}
        keyExtractor={(p) => String(p.payrollId)}
        refreshing={loading}
        onRefresh={load}
        contentContainerStyle={{ padding: spacing(2), paddingBottom: spacing(5) }}
        renderItem={({ item }) => (
          <Card style={styles.card}>
            <Text style={styles.month}>{monthName(item.payrollMonth)}</Text>
            <Text style={[styles.net, { color: item.isRecovery ? colors.danger : colors.success }]}>
              {item.isRecovery ? `Recovery: Rs. ${Math.abs(item.netPayable).toFixed(2)}` : `Rs. ${item.netPayable.toFixed(2)}`}
            </Text>
            <Text style={styles.meta}>
              Gross: Rs. {item.grossSalary.toFixed(2)} · Deductions: Rs. {item.totalDeductions.toFixed(2)} · Present: {item.presentDays}d
            </Text>
            <Button title="View full slip" variant="outline" onPress={() => navigation.navigate('PayslipDetail', { payrollId: item.payrollId })} />
          </Card>
        )}
        ListEmptyComponent={
          !loading ? (
            <Text style={styles.empty}>No payslips for {year}. Payroll is generated by HR each month.</Text>
          ) : null
        }
      />
    </View>
  );
}

function monthName(dateStr: string) {
  return new Date(dateStr).toLocaleDateString('en-US', { month: 'long', year: 'numeric' });
}

const styles = StyleSheet.create({
  screen: { flex: 1, backgroundColor: colors.background },
  yearRow: { flexDirection: 'row', alignItems: 'center', justifyContent: 'space-between', padding: spacing(2) },
  yearLabel: { fontSize: 18, fontWeight: '800', color: colors.text },
  card: { marginBottom: spacing(1.5) },
  month: { fontSize: 15, fontWeight: '700', color: colors.text, marginBottom: 4 },
  net: { fontSize: 22, fontWeight: '800', marginBottom: 6 },
  meta: { fontSize: 12, color: colors.textMuted, marginBottom: spacing(1) },
  empty: { textAlign: 'center', color: colors.textMuted, marginTop: spacing(4) },
});
